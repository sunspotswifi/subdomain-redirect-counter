<?php
/**
 * Sunrise installer class.
 *
 * Automates installing the sunrise handler on multisite: writes a small
 * loader stub to wp-content/sunrise.php that requires the plugin's own
 * sunrise.php (so plugin updates take effect without re-copying), and can
 * add the SUNRISE constant to wp-config.php when it is writable.
 *
 * @package Subdomain_Redirect_Counter
 * @since 1.6.0
 */

// Prevent direct access.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Installs, upgrades, and removes the wp-content/sunrise.php loader stub.
 *
 * @since 1.6.0
 */
class SRC_Sunrise_Installer {

	/**
	 * Marker identifying a stub generated by this plugin.
	 *
	 * The version suffix ("v1") lets future releases rewrite outdated stubs.
	 */
	const STUB_MARKER = 'SRC_SUNRISE_LOADER';

	/**
	 * Current loader stub format version.
	 */
	const STUB_VERSION = 1;

	/**
	 * Comment appended to the wp-config.php line we add, so uninstall can
	 * identify and remove exactly our line and never a user-authored one.
	 */
	const CONFIG_COMMENT = '// Added by Subdomain Redirect Counter.';

	/**
	 * Get the path of the sunrise loader stub.
	 *
	 * @return string
	 */
	public static function get_stub_path(): string {
		return WP_CONTENT_DIR . '/sunrise.php';
	}

	/**
	 * Build the loader stub contents.
	 *
	 * The stub resolves the plugin directory at runtime (WP_PLUGIN_DIR is only
	 * pre-defined at sunrise when set in wp-config.php) and no-ops if the
	 * plugin has been deleted, so it can never fatal a site.
	 *
	 * @return string
	 */
	public static function build_stub_contents(): string {
		$marker = self::STUB_MARKER . ' v' . self::STUB_VERSION;

		return <<<PHP
<?php
/**
 * Sunrise loader for the Subdomain Redirect Counter plugin.
 *
 * {$marker}
 *
 * Generated by the plugin — do not edit; it is reinstalled from the plugin
 * settings page. Safe to delete if the plugin has been removed.
 *
 * @package Subdomain_Redirect_Counter
 */

// Exit if accessed directly.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// WP_PLUGIN_DIR is only defined this early when set in wp-config.php.
\$src_sunrise_plugin_dir = defined( 'WP_PLUGIN_DIR' ) ? WP_PLUGIN_DIR : WP_CONTENT_DIR . '/plugins';
\$src_sunrise_handler    = \$src_sunrise_plugin_dir . '/subdomain-redirect-counter/sunrise.php';

if ( file_exists( \$src_sunrise_handler ) ) {
	require \$src_sunrise_handler;
}

unset( \$src_sunrise_plugin_dir, \$src_sunrise_handler );
PHP;
	}

	/**
	 * Check whether stub contents were generated by this plugin.
	 *
	 * @param string $contents The stub file contents.
	 * @return bool
	 */
	public static function is_our_stub( string $contents ): bool {
		return false !== strpos( $contents, self::STUB_MARKER );
	}

	/**
	 * Extract the stub format version from stub contents.
	 *
	 * @param string $contents The stub file contents.
	 * @return int The version, or 0 if not one of our stubs.
	 */
	public static function get_stub_version( string $contents ): int {
		if ( preg_match( '/' . self::STUB_MARKER . ' v(\d+)/', $contents, $matches ) ) {
			return (int) $matches[1];
		}
		return 0;
	}

	/**
	 * Get the state of wp-content/sunrise.php.
	 *
	 * @return string One of 'missing', 'current', 'outdated', 'legacy_copy', or 'foreign'.
	 */
	public static function get_stub_state(): string {
		$stub_path = self::get_stub_path();

		if ( ! file_exists( $stub_path ) ) {
			return 'missing';
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file, no WP_Filesystem context needed.
		$contents = file_get_contents( $stub_path );

		if ( false === $contents ) {
			return 'foreign';
		}

		if ( self::is_our_stub( $contents ) ) {
			return self::get_stub_version( $contents ) >= self::STUB_VERSION ? 'current' : 'outdated';
		}

		// A manual copy of this plugin's sunrise.php (pre-1.6.0 instructions)
		// is ours to replace with the auto-updating loader.
		if ( false !== strpos( $contents, 'src_sunrise_handle_domain_redirect' ) ) {
			return 'legacy_copy';
		}

		return 'foreign';
	}

	/**
	 * Get the full installation status.
	 *
	 * @return array {
	 *     @type bool   $sunrise_defined    Whether the SUNRISE constant is defined.
	 *     @type string $stub               Stub state from get_stub_state().
	 *     @type bool   $stub_writable      Whether the stub (or wp-content) can be written.
	 *     @type string $wp_config_path     Located wp-config.php path, or empty string.
	 *     @type bool   $wp_config_writable Whether wp-config.php can be written.
	 * }
	 */
	public static function get_status(): array {
		$stub_path      = self::get_stub_path();
		$wp_config_path = self::locate_wp_config();

		return array(
			'sunrise_defined'    => defined( 'SUNRISE' ),
			'stub'               => self::get_stub_state(),
			'stub_writable'      => file_exists( $stub_path ) ? wp_is_writable( $stub_path ) : wp_is_writable( WP_CONTENT_DIR ),
			'wp_config_path'     => $wp_config_path,
			'wp_config_writable' => '' !== $wp_config_path && wp_is_writable( $wp_config_path ),
		);
	}

	/**
	 * Locate wp-config.php.
	 *
	 * Mirrors WordPress's own lookup: ABSPATH first, then one directory up
	 * (only when that directory is not itself a WordPress install).
	 *
	 * @return string The path, or empty string if not found.
	 */
	public static function locate_wp_config(): string {
		if ( file_exists( ABSPATH . 'wp-config.php' ) ) {
			return ABSPATH . 'wp-config.php';
		}

		$parent = dirname( ABSPATH );
		if ( file_exists( $parent . '/wp-config.php' ) && ! file_exists( $parent . '/wp-settings.php' ) ) {
			return $parent . '/wp-config.php';
		}

		return '';
	}

	/**
	 * Insert the SUNRISE define into wp-config.php contents.
	 *
	 * Pure string transform (no filesystem access) so it is unit-testable.
	 *
	 * @param string $contents The wp-config.php contents.
	 * @return string|null Modified contents; unchanged contents if SUNRISE is
	 *                     already defined; null if no safe insertion point exists.
	 */
	public static function insert_sunrise_define( string $contents ): ?string {
		if ( preg_match( '/define\s*\(\s*[\'"]SUNRISE[\'"]/i', $contents ) ) {
			return $contents;
		}

		$insertion = "define( 'SUNRISE', true ); " . self::CONFIG_COMMENT . "\n";

		// Insert on the line after the opening PHP tag.
		$tag_pos = strpos( $contents, '<?php' );
		if ( false === $tag_pos ) {
			return null;
		}

		$eol_pos = strpos( $contents, "\n", $tag_pos );
		if ( false === $eol_pos ) {
			return null;
		}

		return substr_replace( $contents, $insertion, $eol_pos + 1, 0 );
	}

	/**
	 * Remove the SUNRISE define line this plugin added from wp-config.php contents.
	 *
	 * Pure string transform (no filesystem access) so it is unit-testable.
	 * Only removes a line carrying our CONFIG_COMMENT marker.
	 *
	 * @param string $contents The wp-config.php contents.
	 * @return array {
	 *     @type string $status   'removed' (our line was removed), 'foreign'
	 *                            (SUNRISE defined but not by us), or 'absent'.
	 *     @type string $contents The (possibly modified) contents.
	 * }
	 */
	public static function remove_sunrise_define( string $contents ): array {
		$our_line = '/^[ \t]*define\s*\(\s*[\'"]SUNRISE[\'"][^\n]*' . preg_quote( self::CONFIG_COMMENT, '/' ) . '[^\n]*\r?\n?/mi';

		if ( preg_match( $our_line, $contents ) ) {
			return array(
				'status'   => 'removed',
				'contents' => preg_replace( $our_line, '', $contents, 1 ),
			);
		}

		if ( preg_match( '/define\s*\(\s*[\'"]SUNRISE[\'"]/i', $contents ) ) {
			return array(
				'status'   => 'foreign',
				'contents' => $contents,
			);
		}

		return array(
			'status'   => 'absent',
			'contents' => $contents,
		);
	}

	/**
	 * Write (or upgrade) the loader stub. Never touches wp-config.php.
	 *
	 * @return true|WP_Error True on success (or already current).
	 */
	public static function install_stub() {
		if ( ! is_multisite() ) {
			return new WP_Error( 'src_not_multisite', __( 'The sunrise handler is only used on multisite.', 'subdomain-redirect-counter' ) );
		}

		$state = self::get_stub_state();

		if ( 'current' === $state ) {
			return true;
		}

		if ( 'foreign' === $state ) {
			return new WP_Error(
				'src_sunrise_foreign',
				__( 'wp-content/sunrise.php already exists and belongs to another plugin. WordPress loads exactly one sunrise.php, so append this plugin\'s sunrise code to the existing file manually instead of overwriting it.', 'subdomain-redirect-counter' )
			);
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- Direct write with graceful failure; WP_Filesystem credentials UI is not warranted for a one-file stub.
		$written = file_put_contents( self::get_stub_path(), self::build_stub_contents() );

		if ( false === $written ) {
			return new WP_Error(
				'src_stub_write_failed',
				__( 'Could not write wp-content/sunrise.php. Check that wp-content is writable, or copy the file manually.', 'subdomain-redirect-counter' )
			);
		}

		return true;
	}

	/**
	 * Full installation: write the stub and add SUNRISE to wp-config.php.
	 *
	 * @return string|WP_Error 'complete' when both steps succeeded (or were
	 *                         already done), 'stub_only' when the stub is in
	 *                         place but wp-config.php must be edited manually,
	 *                         or WP_Error on stub failure.
	 */
	public static function install() {
		$stub_result = self::install_stub();

		if ( is_wp_error( $stub_result ) ) {
			return $stub_result;
		}

		if ( defined( 'SUNRISE' ) ) {
			return 'complete';
		}

		$config_path = self::locate_wp_config();

		if ( '' === $config_path || ! wp_is_writable( $config_path ) ) {
			return 'stub_only';
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file, no WP_Filesystem context needed.
		$contents = file_get_contents( $config_path );

		if ( false === $contents ) {
			return 'stub_only';
		}

		$modified = self::insert_sunrise_define( $contents );

		if ( null === $modified ) {
			return 'stub_only';
		}

		if ( $modified === $contents ) {
			// Constant already present in the file (takes effect next request).
			return 'complete';
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- Direct write with graceful failure and manual fallback path.
		$written = file_put_contents( $config_path, $modified );

		if ( false === $written ) {
			return 'stub_only';
		}

		return 'complete';
	}

	/**
	 * Remove the loader stub and our wp-config.php line, if safe.
	 *
	 * Called on uninstall. The stub is only deleted when it is ours AND the
	 * SUNRISE constant is gone (either it was never defined, or our line was
	 * successfully removed) — deleting the stub while SUNRISE remains defined
	 * would make core's include_once emit a warning on every request.
	 *
	 * @return void
	 */
	public static function maybe_remove_stub(): void {
		$stub_path = self::get_stub_path();

		if ( ! file_exists( $stub_path ) ) {
			return;
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file, no WP_Filesystem context needed.
		$stub_contents = file_get_contents( $stub_path );

		if ( false === $stub_contents || ! self::is_our_stub( $stub_contents ) ) {
			return;
		}

		if ( defined( 'SUNRISE' ) ) {
			$config_path = self::locate_wp_config();

			if ( '' === $config_path || ! wp_is_writable( $config_path ) ) {
				return;
			}

			// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file, no WP_Filesystem context needed.
			$config_contents = file_get_contents( $config_path );

			if ( false === $config_contents ) {
				return;
			}

			$result = self::remove_sunrise_define( $config_contents );

			if ( 'removed' !== $result['status'] ) {
				// SUNRISE was defined by someone else — keep the self-guarding stub.
				return;
			}

			// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents -- Direct write with graceful failure.
			$written = file_put_contents( $config_path, $result['contents'] );

			if ( false === $written ) {
				return;
			}
		}

		// phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink -- Removing our own generated stub.
		unlink( $stub_path );
	}
}
